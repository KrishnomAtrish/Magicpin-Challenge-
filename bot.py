from fastapi import FastAPI, Request, Response
from datetime import datetime
import uvicorn
import google.generativeai as genai
import json
import os

# Set up Gemini with your provided API key (Securely via Environment Variable for Render)
api_key = os.environ.get("GEMINI_API_KEY")
if not api_key:
    print("WARNING: GEMINI_API_KEY not found in environment variables!")
genai.configure(api_key=api_key)
model = genai.GenerativeModel('gemini-3.8-flash')

app = FastAPI()

state = {
    "contexts_loaded": { "category": 0, "merchant": 0, "customer": 0, "trigger": 0 },
    "start_time": datetime.now(),
    "contexts": {}
}

@app.get("/v1/healthz")
async def healthz():
    return {
        "status": "ok",
        "uptime_seconds": int((datetime.now() - state["start_time"]).total_seconds()),
        "contexts_loaded": state["contexts_loaded"]
    }

@app.get("/v1/metadata")
async def metadata():
    return {
        "team_name": "Team AI",
        "team_members": ["Vera Bot"],
        "model": "gemini-3.8-flash",
        "approach": "Dynamic context-aware message generation using Gemini API.",
        "version": "1.0.0"
    }

@app.post("/v1/context")
async def context(request: Request, response: Response):
    data = await request.json()
    scope = data.get("scope")
    context_id = data.get("context_id")
    version = data.get("version")
    
    key = f"{scope}_{context_id}"
    
    if key in state["contexts"]:
        current_version = state["contexts"][key]["version"]
        if current_version >= version:
            response.status_code = 409
            return {"accepted": False, "reason": "stale_version", "current_version": current_version}
        
    if key not in state["contexts"]:
        if scope in state["contexts_loaded"]:
            state["contexts_loaded"][scope] += 1
            
    state["contexts"][key] = {"version": version, "payload": data.get("payload")}
    
    return {
        "accepted": True,
        "ack_id": f"ack_{context_id}_v{version}",
        "stored_at": datetime.now().isoformat() + "Z"
    }

@app.post("/v1/tick")
async def tick(request: Request):
    data = await request.json()
    available_triggers = data.get("available_triggers", [])
    if not available_triggers:
        return {"actions": []}
        
    actions = []
    
    for trigger_id in available_triggers[:3]:
        trigger_context = state["contexts"].get(f"trigger_{trigger_id}", {}).get("payload", {})
        merchant_id = trigger_context.get("merchant_id")
        merchant_context = state["contexts"].get(f"merchant_{merchant_id}", {}).get("payload", {})
        category_slug = merchant_context.get("category_slug")
        category_context = state["contexts"].get(f"category_{category_slug}", {}).get("payload", {})
        
        prompt = f"""
        You are Vera, an AI assistant helping a merchant.
        Merchant details: {json.dumps(merchant_context)}
        Category rules: {json.dumps(category_context)}
        Trigger to act on: {json.dumps(trigger_context)}
        
        Compose a short, highly-compelling message for this merchant based on the trigger. 
        It MUST be specific and follow category voice rules. Provide a reason for the message.
        
        Return ONLY valid JSON in this exact structure without markdown backticks:
        {{
            "body": "The actual message to send to the merchant",
            "rationale": "Why you chose to say this",
            "cta": "open_ended"
        }}
        """
        
        try:
            response = await model.generate_content_async(prompt)
            text = response.text.strip()
            
            import re
            match = re.search(r'\{.*\}', text, re.DOTALL)
            if match:
                text = match.group(0)
                
            result = json.loads(text.strip())
            
            actions.append({
              "conversation_id": f"conv_{trigger_id}",
              "merchant_id": merchant_id,
              "customer_id": None,
              "send_as": "vera",
              "trigger_id": trigger_id,
              "template_name": "dynamic_gen",
              "template_params": [],
              "body": result.get("body", "Hi, I have an update for you."),
              "cta": result.get("cta", "open_ended"),
              "suppression_key": f"supp_{trigger_id}",
              "rationale": result.get("rationale", "Generated by Gemini")
            })
        except Exception as e:
            print("Error generating tick content:", e)
            
    return {"actions": actions[:20]}

@app.post("/v1/reply")
async def reply(request: Request):
    data = await request.json()
    message = data.get("message", "").lower()
    merchant_id = data.get("merchant_id")
    
    if "stop" in message or "not interested" in message or "spam" in message:
        return {
            "action": "end",
            "rationale": "Merchant explicitly opted out."
        }
    if "auto-reply" in message or "contacting" in message or "respond shortly" in message:
        state["auto_replies"] = state.get("auto_replies", {})
        state["auto_replies"][merchant_id] = state["auto_replies"].get(merchant_id, 0) + 1
        
        if state["auto_replies"][merchant_id] >= 3:
            return {
                "action": "end",
                "rationale": "Too many auto-replies. Ending conversation."
            }
            
        return {
            "action": "wait",
            "wait_seconds": 14400,
            "rationale": "Detected merchant auto-reply. Waiting."
        }
        
    merchant_context = state["contexts"].get(f"merchant_{merchant_id}", {}).get("payload", {})
    
    prompt = f"""
    You are Vera, AI assistant for this merchant: {json.dumps(merchant_context)}.
    The merchant just replied: "{message}"
    
    Provide a brief, helpful reply to keep the conversation moving and achieve their goal.
    Return ONLY valid JSON in this exact structure without markdown backticks:
    {{
        "body": "The reply message",
        "rationale": "Why you replied this way"
    }}
    """
    
    try:
        response = await model.generate_content_async(prompt)
        text = response.text.strip()
        
        # Try to safely extract JSON if the model added extra text
        import re
        match = re.search(r'\{.*\}', text, re.DOTALL)
        if match:
            text = match.group(0)
            
        result = json.loads(text.strip())
        
        return {
            "action": "send",
            "body": result.get("body", "Got it, I'll assist you with that."),
            "cta": "open_ended",
            "rationale": result.get("rationale", "Generated reply based on merchant intent.")
        }
    except Exception as e:
        print(f"Error generating reply for '{message}':", e)
        # If they said no thanks, let's gracefully end rather than looping
        if "no" in message.lower():
            return {"action": "end", "rationale": "Merchant declined."}
            
        return {
            "action": "send",
            "body": "I'm having a little trouble understanding. Could you clarify?",
            "cta": "open_ended",
            "rationale": "Fallback due to JSON parsing error or rate limit."
        }

if __name__ == "__main__":
    uvicorn.run(app, host="0.0.0.0", port=8080)
